package ru.akvine.istochnik.services.impl;

import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import ru.akvine.compozit.commons.istochnik.ColumnDto;
import ru.akvine.compozit.commons.istochnik.GenerateTableRequest;
import ru.akvine.compozit.commons.utils.Asserts;
import ru.akvine.istochnik.config.schema.SchemaConversionProperties;
import ru.akvine.istochnik.exceptions.SchemaConversionDisabledException;
import ru.akvine.istochnik.exceptions.SchemaConversionException;
import ru.akvine.istochnik.providers.SchemaParsersProvider;
import ru.akvine.istochnik.services.SchemaConversionService;
import ru.akvine.istochnik.services.dto.schema.ConvertSchema;
import ru.akvine.istochnik.services.dto.schema.ConvertedSchema;
import ru.akvine.istochnik.services.schema.ColumnSchema;
import ru.akvine.istochnik.services.schema.ParsedSchema;
import ru.akvine.istochnik.services.schema.SchemaColumnMapper;
import ru.akvine.istochnik.services.schema.TableSchema;

@Service
@RequiredArgsConstructor
public class SchemaConversionServiceImpl implements SchemaConversionService {
    private final SchemaConversionProperties schemaConversionProperties;
    private final SchemaParsersProvider schemaParsersProvider;
    private final SchemaColumnMapper schemaColumnMapper;

    @Override
    public boolean isEnabled() {
        return schemaConversionProperties.isEnabled();
    }

    @Override
    public ConvertedSchema convert(ConvertSchema convertSchema) {
        Asserts.isNotNull(convertSchema);
        if (!isEnabled()) {
            throw new SchemaConversionDisabledException();
        }

        ParsedSchema schema =
                schemaParsersProvider.getByType(convertSchema.getType()).parse(convertSchema.getContent());
        if (schema.tables().isEmpty()) {
            throw new SchemaConversionException("Schema doesn't contain table definitions");
        }

        List<String> warnings = new ArrayList<>(schema.warnings());
        List<GenerateTableRequest> requests = new ArrayList<>();
        LocalDate today = LocalDate.now();
        for (TableSchema table : schema.tables()) {
            List<ColumnDto> columns = convertColumns(table, convertSchema.getSize(), today, warnings);
            if (columns.isEmpty()) {
                warnings.add("Table [" + table.getName() + "]: there are no columns to generate, table is skipped");
                continue;
            }

            requests.add(new GenerateTableRequest()
                    .setTableName(table.getName())
                    .setSize(convertSchema.getSize())
                    .setFileType(convertSchema.getFileType().getExtension())
                    .setColumns(columns));
        }

        if (requests.isEmpty()) {
            throw new SchemaConversionException(
                    "Schema doesn't contain tables with columns to generate: " + String.join(". ", warnings));
        }
        return new ConvertedSchema().setRequests(requests).setWarnings(warnings);
    }

    private List<ColumnDto> convertColumns(TableSchema table, int size, LocalDate today, List<String> warnings) {
        List<ColumnDto> columns = new ArrayList<>();
        for (ColumnSchema column : table.getColumns()) {
            // Значение такой колонки задаёт только сама база данных: в INSERT её быть не должно
            if (column.isDatabaseGenerated()) {
                warnings.add("Table [" + table.getName() + "], column [" + column.getName()
                        + "]: value is always generated by database, column is skipped");
                continue;
            }
            columns.add(schemaColumnMapper.map(table.getName(), column, size, today, warnings));
        }
        return columns;
    }
}
