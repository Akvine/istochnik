-- Миграция в стиле Flyway (PostgreSQL): перечисление, три таблицы и изменения после их создания.
-- По ней POST /v1/schemas/convert возвращает три запроса на генерацию.

CREATE TYPE order_status AS ENUM ('NEW', 'PAID', 'SHIPPED', 'CANCELLED');

CREATE TABLE customers (
    id          BIGSERIAL PRIMARY KEY,
    external_id UUID           NOT NULL,
    email       VARCHAR(255)   NOT NULL UNIQUE,
    full_name   VARCHAR(100)   NOT NULL,
    birth_date  DATE,
    balance     NUMERIC(12, 2) NOT NULL DEFAULT 0,
    is_active   BOOLEAN        NOT NULL DEFAULT true,
    settings    JSONB          NOT NULL DEFAULT '{}',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE orders (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id BIGINT         NOT NULL REFERENCES customers (id),
    status      order_status   NOT NULL DEFAULT 'NEW',
    total       NUMERIC(10, 2) NOT NULL CHECK (total >= 0),
    -- Вычисляемую колонку заполняет база данных: в запрос на генерацию она не попадёт
    total_with_tax NUMERIC(10, 2) GENERATED ALWAYS AS (total * 1.2) STORED,
    comment     TEXT,
    created_at  TIMESTAMP      NOT NULL DEFAULT now(),
    CONSTRAINT orders_pk PRIMARY KEY (id)
);

CREATE TABLE order_items (
    order_id    BIGINT   NOT NULL,
    line_number SMALLINT NOT NULL,
    product     VARCHAR(50) NOT NULL,
    quantity    INTEGER  NOT NULL,
    price       NUMERIC(10, 2) NOT NULL,
    -- Составной ключ: уникальной станет его первая колонка
    PRIMARY KEY (order_id, line_number),
    FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
);

-- Изменения после создания таблиц тоже учитываются
ALTER TABLE customers ADD COLUMN phone VARCHAR(20);
ALTER TABLE orders ALTER COLUMN comment SET NOT NULL;
CREATE UNIQUE INDEX customers_external_id_idx ON customers (external_id);

-- Остальные операторы пропускаются
CREATE INDEX orders_status_idx ON orders (status);
COMMENT ON TABLE customers IS 'Покупатели';
